// ============================================================
// build-design-docs.mjs
// ------------------------------------------------------------
// Generates the design-system files that must never be hand-edited, from the
// sources that own their content:
//
//   styles/zeros-tokens.css          ← styles/tokens/*.tokens.json + resolver
//   apps/marketing/src/index.css     ← same values, marketing export groups
//   docs/design-tokens.md            ← styles/zeros-tokens.css,
//                                       styles/global/platform.css,
//                                       styles/policy/contrast-contract.json
//   .claude/skills/zeros-ui/SKILL.md  ┐
//   .agents/skills/zeros-ui/SKILL.md  ├ ← the agent brief in docs/design-system.md
//   .cursor/rules/zeros-ui.mdc        ┘   (between the agent-brief markers)
//
//   pnpm design:docs           write them
//   pnpm check:ui              fails if any is stale (checkGeneratedDocs)
// ============================================================
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import { buildTokens, MARKETING_TOKENS_FILE, renderTokenCss } from "./build-tokens.mjs";
import {
  evaluateContract,
  evaluateLadders,
  extractBlock,
  readThemes,
  resolveRgb,
  resolveValue,
  toHex,
  TOKENS_FILE,
} from "./token-palette.mjs";
import { SPACING_STEPS } from "./ui-policy.mjs";

const CONTRACT_FILE = "styles/policy/contrast-contract.json";
const GUIDE_FILE = "docs/design-system.md";
const BRIEF_START = "<!-- agent-brief:start -->";
const BRIEF_END = "<!-- agent-brief:end -->";
const GENERATOR = "scripts/design-system/build-design-docs.mjs";

const NEUTRAL_GROUPS = [
  ["Surfaces", ["bg0", "bg1", "bg1-hover", "bg1-highlight", "bg1-bright", "bg2", "bg2-hover", "bg2-highlight", "bg3", "bg3-hover", "bg4", "bg5", "sidebar-bg", "sidebar-bg-hover", "highlighted-bg"]],
  ["Text and icons", ["fg1", "fg2", "fg3", "muted-fg"]],
  ["Borders and focus", ["border1", "border2", "border3", "border4", "highlighted-bright"]],
  ["Inverted pair and primary button", ["inverted-bg", "inverted-fg", "primary-button-bg", "primary-button-hover", "primary-button-fg"]],
];
const FAMILIES = [
  ["red", "error · −N"],
  ["green", "success · +N"],
  ["yellow", "warning · modified · in progress"],
  ["blue", "info · links"],
  ["violet", "done · merged"],
  ["brown", "file paths · warm accents"],
];

// Roles for tokens whose stylesheet comment is only a hex value or alias note.
const ROLE_FALLBACK = {
  "sidebar-bg": "repository sidebar background",
  "sidebar-bg-hover": "sidebar row hover + selected state",
  "inverted-bg": "polarity-flipping fill (near-white in Dark, near-black in Light)",
  "primary-button-bg": "filled focal CTA (one per view)",
  "primary-button-fg": "text/icon on the primary button",
};

/** `--token: value; /* comment *\/` descriptions from a CSS block. */
function tokenDescriptions(block) {
  const out = new Map();
  for (const match of block.matchAll(/--([a-z0-9-]+):\s*[^;]+;\s*\/\*\s*([\s\S]*?)\s*\*\//g)) {
    const comment = match[2].replace(/\s+/g, " ").trim();
    const dash = comment.indexOf("—");
    out.set(match[1], (dash === -1 ? comment : comment.slice(dash + 1)).trim());
  }
  return out;
}

function swatch(theme, name) {
  const value = theme.get(name);
  const alias = value?.match(/^var\(\s*--([a-z0-9-]+)\s*\)$/);
  const hex = toHex(resolveRgb(theme, name));
  return alias ? `\`${hex}\` (= ${alias[1]})` : `\`${hex}\``;
}

function themeKeys(css, prefix) {
  const theme = extractBlock(css, "@theme inline");
  const out = [];
  for (const match of theme.matchAll(new RegExp(`--(${prefix}[a-z0-9-]*):\\s*([^;]+);`, "g"))) {
    out.push([match[1], match[2].trim()]);
  }
  return out;
}

export function renderTokenReference(root) {
  const css = renderTokenCss(root);
  const themes = readThemes(root, css);
  const describe = tokenDescriptions(extractBlock(css, ":root"));
  const contract = JSON.parse(readFileSync(join(root, CONTRACT_FILE), "utf8"));
  const role = (token) => {
    const text = describe.get(token) ?? "";
    return ROLE_FALLBACK[token] ?? (/^(?:#[0-9a-f]{6}|=)/i.test(text) || !text ? "" : text);
  };
  const lines = [
    "# Zeros design tokens (generated)",
    "",
    `<!-- GENERATED by ${GENERATOR} from styles/tokens/ via ${TOKENS_FILE}, styles/global/platform.css and ${CONTRACT_FILE}. Do not edit; run \`pnpm design:docs\`. -->`,
    "",
    "Values for every public token in both themes, the contrast each declared pairing achieves, and the scales the policy checks enforce. How to choose a token: [design-system.md](design-system.md).",
    "",
  ];

  lines.push("## Neutral palette", "");
  for (const [title, tokens] of NEUTRAL_GROUPS) {
    lines.push(`### ${title}`, "", "| Token | Dark | Light | Role |", "| --- | --- | --- | --- |");
    for (const token of tokens) {
      lines.push(
        `| \`--${token}\` | ${swatch(themes.dark, token)} | ${swatch(themes.light, token)} | ${role(token)} |`,
      );
    }
    lines.push("");
  }

  lines.push(
    "## Status families",
    "",
    "`-primary` is status text / counts / icons on app surfaces, `-bg` a tinted container, `-fg` the text on that container. Numeric ramps (`--red-500` …) are private to `styles/zeros-tokens.css`.",
    "",
    "| Family | Meaning | Role | Dark | Light |",
    "| --- | --- | --- | --- | --- |",
  );
  for (const [family, meaning] of FAMILIES) {
    const roles = ["primary", "bg", "fg"];
    if (family === "red") roles.push("secondary", "secondary-hover", "secondary-fg");
    if (family === "yellow") roles.push("icon");
    roles.forEach((role, index) => {
      const token = `${family}-${role}`;
      lines.push(
        `| ${index === 0 ? family : ""} | ${index === 0 ? meaning : ""} | \`--${token}\` | ${swatch(themes.dark, token)} | ${swatch(themes.light, token)} |`,
      );
    });
  }
  lines.push("");

  lines.push(
    "## Contrast contract",
    "",
    `Worst WCAG 2.2 ratio over each declared pairing's surfaces (\`${CONTRACT_FILE}\`). \`@rest\` = ${contract.surfaces.rest.join(", ")}; \`@hover\` = ${contract.surfaces.hover.join(", ")}.`,
    "",
    "Supplemental metadata and subtle boundary floors are owner-reviewed design decisions, below AA and WCAG 1.4.11 respectively. Passing those floors is not a WCAG conformance claim.",
    "",
    "| Foreground | On | Needs | Dark (worst) | Light (worst) |",
    "| --- | --- | --- | --- | --- |",
  );
  const results = evaluateContract(contract, themes);
  for (const pair of contract.pairs) {
    const on = Array.isArray(pair.on) ? pair.on.join(", ") : pair.on;
    for (const fg of pair.fg) {
      const cell = (theme) => {
        const rows = results.filter(
          (r) => r.theme === theme && r.fg === fg && r.role === pair.role && (Array.isArray(pair.on) ? pair.on : [pair.on]).some((ref) => (ref.startsWith("@") ? contract.surfaces[ref.slice(1)].includes(r.surface) : ref === r.surface)),
        );
        const worst = rows.reduce((a, b) => (b.ratio < a.ratio ? b : a));
        return `${worst.pass ? "✓" : "✗"} ${worst.ratio.toFixed(2)} on ${worst.surface}`;
      };
      lines.push(`| \`--${fg}\` | ${on} | ${contract.roles[pair.role].min}:1 | ${cell("dark")} | ${cell("light")} |`);
    }
  }
  lines.push("", "Contrast ladders (each upper tier must have at least the listed factor more contrast on its declared surface):", "", "| Step | On | Needs | Dark | Light |", "| --- | --- | --- | --- | --- |");
  const ladders = evaluateLadders(contract, themes);
  for (const step of ladders.filter((r) => r.theme === "dark")) {
    const light = ladders.find((r) => r.theme === "light" && r.upper === step.upper && r.lower === step.lower && r.on === step.on);
    lines.push(`| ${step.upper} → ${step.lower} | ${step.on} | ${step.minStep}× | ${step.step.toFixed(2)}× | ${light.step.toFixed(2)}× |`);
  }
  lines.push("");

  lines.push("## Scales", "", "### Type", "", "| Utility | Size | Line height |", "| --- | --- | --- |");
  const resolveVar = (value) => {
    const alias = value.match(/^var\(--([a-z0-9-]+)\)$/);
    return alias ? resolveValue(themes.dark, alias[1]) : value;
  };
  const px = (value) => {
    const resolved = resolveVar(value);
    return resolved.endsWith("rem") ? `${parseFloat(resolved) * 16}px` : resolved;
  };
  const text = themeKeys(css, "text-");
  for (const [key, value] of text) {
    if (key.includes("--")) continue;
    const size = px(value);
    const ratio = text.find(([k]) => k === `${key}--line-height`)?.[1];
    const fraction = ratio?.match(/^calc\(\s*([\d.]+)\s*\/\s*([\d.]+)\s*\)$/);
    const lineHeight = !ratio
      ? "inherited"
      : fraction
        ? `${Math.round((parseFloat(size) * Number(fraction[1])) / Number(fraction[2]))}px`
        : ratio;
    lines.push(`| \`${key}\` | ${size} | ${lineHeight} |`);
  }
  lines.push(
    "| `text-sm` | 14px | 20px (Tailwind default) |",
    "",
    "Weights: `font-normal` 400 · `font-medium` " +
      `${resolveValue(themes.dark, "weight-medium")} · \`font-semibold\` ${resolveValue(themes.dark, "weight-semibold")} · \`font-bold\` ${resolveValue(themes.dark, "weight-bold")}.`,
    "",
    "### Radius",
    "",
    "| Utility | Value |",
    "| --- | --- |",
  );
  for (const [key, value] of themeKeys(css, "radius-")) {
    if (key.includes("*")) continue;
    lines.push(`| \`rounded-${key.slice("radius-".length)}\` | ${value} |`);
  }
  lines.push(
    "",
    "### Spacing",
    "",
    `Allowed Tailwind spacing steps (×4px): ${[...SPACING_STEPS].sort((a, b) => a - b).join(" · ")} — plus \`px\` (1px).`,
    "",
    "### Stacking layers",
    "",
    "| Utility | z-index |",
    "| --- | --- |",
  );
  const platform = readFileSync(join(root, "styles/global/platform.css"), "utf8");
  for (const match of platform.matchAll(/--z-([a-z]+):\s*(\d+);/g)) {
    lines.push(`| \`z-${match[1]}\` | ${match[2]} |`);
  }
  lines.push("");
  return `${lines.join("\n")}\n`;
}

export function agentBrief(root) {
  const guide = readFileSync(join(root, GUIDE_FILE), "utf8");
  const start = guide.indexOf(BRIEF_START);
  const end = guide.indexOf(BRIEF_END);
  if (start === -1 || end === -1 || end < start) {
    throw new Error(`${GUIDE_FILE} must contain ${BRIEF_START} … ${BRIEF_END}`);
  }
  return guide.slice(start + BRIEF_START.length, end).trim();
}

const SKILL_DESCRIPTION =
  "Zeros design system for renderer UI: use when building or changing UI under apps/desktop/src/renderer or styles/ — components, tokens, colors, spacing, typography, contrast, and the checks that gate them.";

export function renderAgentFiles(root) {
  const brief = agentBrief(root);
  const notice = `<!-- GENERATED from ${GUIDE_FILE} by ${GENERATOR}. Edit the agent brief there, then run \`pnpm design:docs\`. -->`;
  // JSON string syntax is valid YAML and quotes the description's colon.
  const description = JSON.stringify(SKILL_DESCRIPTION);
  const skill = `---\nname: zeros-ui\ndescription: ${description}\n---\n\n${notice}\n\n${brief}\n`;
  return {
    ".claude/skills/zeros-ui/SKILL.md": skill,
    ".agents/skills/zeros-ui/SKILL.md": skill,
    ".cursor/rules/zeros-ui.mdc": `---\ndescription: ${description}\nglobs: apps/desktop/src/renderer/**,styles/**\nalwaysApply: false\n---\n\n${notice}\n\n${brief}\n`,
  };
}

export function generatedFiles(root) {
  return {
    "docs/design-tokens.md": renderTokenReference(root),
    ...renderAgentFiles(root),
  };
}

/** check:ui hook — one violation per stale or missing generated file. */
export function checkGeneratedDocs(root) {
  const violations = [];
  for (const [rel, content] of Object.entries(generatedFiles(root))) {
    const path = join(root, rel);
    if (!existsSync(path) || readFileSync(path, "utf8") !== content) {
      violations.push({
        file: rel,
        line: 1,
        message: `Generated design-system file is stale — run \`pnpm design:docs\` (source: ${rel === "docs/design-tokens.md" ? `styles/tokens/ + ${CONTRACT_FILE}` : GUIDE_FILE}).`,
      });
    }
  }
  return violations;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const root = process.cwd();
  buildTokens(root);
  console.log(`wrote ${TOKENS_FILE}`);
  console.log(`wrote ${MARKETING_TOKENS_FILE}`);
  for (const [rel, content] of Object.entries(generatedFiles(root))) {
    const path = join(root, rel);
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, content);
    console.log(`wrote ${rel}`);
  }
}
