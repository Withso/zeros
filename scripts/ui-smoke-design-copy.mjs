import { expect } from "@playwright/test";
import { designFrameElementBox } from "./ui-smoke-design-helpers.mjs";

const workspaceId = "ws_design_harness";
const displayed = '[data-design-frame="home.html"] iframe[data-design-document-buffer="displayed"][data-design-document-ready]';
async function load(page, node = "home-hero", fixture = "layoutGestures") {
  await page.goto(`${new URL(page.url()).origin}/apps/desktop/src/renderer/harnesses/harness-design-workspace.html?${fixture}&measureManipulation&scopedMutations&engineDelayMs=400`, { waitUntil: "networkidle" });
  await page.locator('[data-design-frame-row="home.html"]').click();
  await page.locator(displayed).waitFor();
  await page.evaluate(() => window.__zerosHarnessDesignSurface.ui.getState().setViewport("ws_design_harness", { zoom: 0.5, panX: 80, panY: 100 }));
  const row = page.locator(`[data-design-sidebar-panel] [data-design-layer-id="${node}"]`);
  for (let i = 0; i < 8 && !await row.isVisible(); i++) {
    const folded = page.locator('[data-design-sidebar-panel] [role="treeitem"][aria-expanded="false"]:visible').first();
    if (!await folded.count()) break;
    await folded.locator("[data-layer-disclosure]").click();
  }
  await row.click();
  await page.locator(`[data-design-selected-element][data-design-element-overlay="${node}"]`).waitFor();
  await settled(page);
  return page.frameLocator(displayed);
}
const settled = page => page.waitForFunction(id => !window.__zerosHarnessDesignSurface.measurement.editing(id), workspaceId);
const hold = page => page.evaluate(() => window.__zerosHarnessDesignSurface.measurement.hold("design.transaction.apply"));
const release = page => page.evaluate(() => window.__zerosHarnessDesignSurface.measurement.release("design.transaction.apply"));
const selection = page => page.evaluate(id => window.__zerosHarnessDesignSurface.ui.getState().byWorkspace[id].selectedNodeId, workspaceId);
const copies = frame => frame.locator('[data-oid^="home-hero-copy-"]').filter({ has: frame.locator('[data-oid$="-home-heading"]') });

/** Held source writes exercise real shortcuts and pointer handling. These are
 * continuity/correctness assertions; they do not certify presentation latency. */
export async function runDesignCopySmoke({ page, check }) {
  await page.setViewportSize({ width: 1600, height: 1000 });
  let frame = await load(page);
  const original = await frame.locator('[data-oid="home-hero"]').evaluate(node => node.outerHTML);
  const originalDocument = await page.locator(displayed).elementHandle();
  await hold(page);
  const viewport = page.locator('[data-design-canvas-viewport]');
  await viewport.focus();
  for (let i = 0; i < 5; i++) await page.keyboard.press("Control+d");
  await expect(copies(frame).filter({ has: frame.locator('[data-oid$="-home-heading"]') })).toHaveCount(5);
  expect(await frame.locator('[data-oid="home-hero"]').evaluate(node => node.outerHTML)).toBe(original);
  await release(page);
  await settled(page);
  await expect.poll(() => selection(page)).toMatch(/^home-hero-copy-/);
  expect(await originalDocument.evaluate(node => node.isConnected)).toBe(true);
  check("five queued keyboard copies paint before persistence and keep the original document mounted", true);

  const selected = await selection(page);
  await hold(page);
  await viewport.focus();
  await page.keyboard.press("Backspace");
  await expect(frame.locator(`[data-oid="${selected}"]`)).toHaveCount(0);
  await release(page);
  await settled(page);
  expect(await originalDocument.evaluate(node => node.isConnected)).toBe(true);
  await page.keyboard.press("Control+z");
  await expect(frame.locator(`[data-oid="${selected}"]`)).toHaveCount(1);
  await settled(page);
  check("nested deletion paints before persistence and Undo restores the same live document", true);

  frame = await load(page, "home-heading");
  const before = await frame.locator('[data-oid="home-heading"]').evaluate(node => node.outerHTML);
  const box = await designFrameElementBox(page.locator(displayed), frame.locator('[data-oid="home-heading"]'));
  await hold(page);
  await page.keyboard.down("Alt");
  await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2);
  await page.mouse.down();
  await page.mouse.move(box.x + box.width / 2 + 120, box.y + box.height / 2 + 170, { steps: 12 });
  await expect(frame.locator('[data-oid^="copy-"]')).toHaveCount(1);
  expect(await frame.locator('[data-oid="home-heading"]').evaluate(node => node.outerHTML)).toBe(before);
  await page.mouse.up();
  await page.keyboard.up("Alt");
  await release(page);
  await settled(page);
  await expect.poll(() => selection(page)).toMatch(/^copy-/);
  const copyId = await selection(page);
  expect(await frame.locator(`[data-oid="${copyId}"]`).evaluate(node => node.parentElement.getAttribute("data-oid"))).toBe("home-main");
  expect(await frame.locator('[data-oid="home-heading"]').evaluate(node => node.outerHTML)).toBe(before);
  await viewport.focus();
  await page.keyboard.press("Control+z");
  await expect(frame.locator(`[data-oid="${copyId}"]`)).toHaveCount(0);
  await settled(page);
  check("Option drag preserves the original, nests the copy at release, and undoes in one step", true);

  frame = await load(page, "home-heading");
  const cancelled = await designFrameElementBox(page.locator(displayed), frame.locator('[data-oid="home-heading"]'));
  await page.keyboard.down("Alt");
  await page.mouse.move(cancelled.x + cancelled.width / 2, cancelled.y + cancelled.height / 2);
  await page.mouse.down();
  await page.mouse.move(cancelled.x + cancelled.width / 2 + 90, cancelled.y + cancelled.height / 2 + 140, { steps: 8 });
  await expect(frame.locator('[data-oid^="copy-"]')).toHaveCount(1);
  await page.keyboard.press("Escape");
  await page.mouse.up();
  await page.keyboard.up("Alt");
  await expect(frame.locator('[data-oid^="copy-"]')).toHaveCount(0);
  expect(await page.evaluate(() => window.__zerosHarnessDesignSurface.measurement.requests.filter(request => request.op === "design.transaction.apply").length)).toBe(0);
  check("Escape retires an Option-drag preview without submitting a write", true);

  frame = await load(page, "home-heading");
  await page.evaluate(() => window.__zerosHarnessDesignSurface.ui.getState().setViewport("ws_design_harness", { zoom: 0.25, panX: 80, panY: 140 }));
  const moving = await designFrameElementBox(page.locator(displayed), frame.locator('[data-oid="home-heading"]'));
  const destination = await page.locator('[data-design-frame="pricing.html"]').boundingBox();
  const originalSource = await frame.locator('[data-oid="home-heading"]').evaluate(node => node.outerHTML);
  await page.keyboard.down("Alt");
  await page.mouse.move(moving.x + moving.width / 2, moving.y + moving.height / 2);
  await page.mouse.down();
  await page.mouse.move(destination.x + destination.width / 2, destination.y + destination.height / 2, { steps: 16 });
  await page.mouse.up();
  await page.keyboard.up("Alt");
  await expect.poll(() => page.evaluate(id => window.__zerosHarnessDesignSurface.ui.getState().byWorkspace[id].selectedFrame, workspaceId)).toBe("pricing.html");
  await settled(page);
  const target = page.frameLocator('[data-design-frame="pricing.html"] iframe[data-design-document-buffer="displayed"][data-design-document-ready]');
  const copied = await selection(page);
  expect(copied).toMatch(/^copy-/);
  await expect(target.locator(`[data-oid="${copied}"]`)).toHaveCount(1);
  expect(await frame.locator('[data-oid="home-heading"]').evaluate(node => node.outerHTML)).toBe(originalSource);
  await viewport.focus();
  await page.keyboard.press("Backspace");
  await expect(target.locator(`[data-oid="${copied}"]`)).toHaveCount(0);
  await settled(page);
  check("Option drag copies into another frame and immediate Delete targets the destination", true);

  await load(page);
  await page.evaluate(() => window.__zerosHarnessDesignSurface.measurement.hold("design.frame.duplicate"));
  const home = page.locator('[data-design-frame="home.html"]');
  const rootBefore = await home.boundingBox();
  const label = await home.locator('[data-design-frame-label]').boundingBox();
  await page.keyboard.down("Alt");
  await page.keyboard.down("Control");
  await page.mouse.move(label.x + label.width / 2, label.y + label.height / 2);
  await page.mouse.down();
  await page.mouse.move(label.x + label.width / 2 + 100, label.y + label.height / 2 + 140, { steps: 12 });
  expect(await home.boundingBox()).toEqual(rootBefore);
  await page.mouse.up();
  await page.keyboard.up("Alt");
  await page.keyboard.up("Control");
  await page.waitForFunction(() => window.__zerosHarnessDesignSurface.measurement.requests.some(request => request.op === "design.frame.duplicate"));
  await page.evaluate(() => window.__zerosHarnessDesignSurface.measurement.release("design.frame.duplicate"));
  await settled(page);
  await expect(page.locator('[data-design-frame="copy-1.html"]')).toHaveCount(1);
  expect(await home.boundingBox()).toEqual(rootBefore);
  await viewport.focus();
  await page.keyboard.press("Control+z");
  await expect(page.locator('[data-design-frame="copy-1.html"]')).toHaveCount(0);
  await settled(page);
  check("Option drag copies a top-level frame at release without moving its original and undoes in one step", true);

  frame = await load(page, "home-heading", "autoLayout");
  const sidebar = page.locator('[data-design-sidebar-panel]');
  await sidebar.locator('[data-design-layer-id="home-copy"]').click({ modifiers: ["Shift"] });
  await page.waitForFunction(id => window.__zerosHarnessDesignSurface.ui.getState().byWorkspace[id].selectedNodeIds.length === 2, workspaceId);
  const originals = await frame.locator('[data-oid="home-heading"], [data-oid="home-copy"]').evaluateAll(nodes => nodes.map(node => node.outerHTML));
  const groupMember = await designFrameElementBox(page.locator(displayed), frame.locator('[data-oid="home-heading"]'));
  await hold(page);
  await page.keyboard.down("Alt");
  await page.mouse.move(groupMember.x + groupMember.width / 2, groupMember.y + groupMember.height / 2);
  await page.mouse.down();
  await page.mouse.move(groupMember.x + groupMember.width / 2 + 40, groupMember.y + groupMember.height / 2 + 45, { steps: 12 });
  await expect(frame.locator('[data-oid^="copy-"]')).toHaveCount(2);
  expect(await frame.locator('[data-oid="home-heading"], [data-oid="home-copy"]').evaluateAll(nodes => nodes.map(node => node.outerHTML))).toEqual(originals);
  await page.mouse.up();
  await page.keyboard.up("Alt");
  await release(page);
  await settled(page);
  await page.waitForFunction(id => window.__zerosHarnessDesignSurface.ui.getState().byWorkspace[id].selectedNodeIds.every(node => node.startsWith("copy-")), workspaceId);
  await viewport.focus();
  await page.keyboard.press("Control+z");
  await expect(frame.locator('[data-oid^="copy-"]')).toHaveCount(0);
  await settled(page);
  check("Option drag copies selected sibling layers together with one undo", true);

  frame = await load(page, "home-heading");
  const hidden = await designFrameElementBox(page.locator(displayed), frame.locator('[data-oid="home-heading"]'));
  await page.keyboard.down("Alt");
  await page.mouse.move(hidden.x + hidden.width / 2, hidden.y + hidden.height / 2);
  await page.mouse.down();
  await page.mouse.move(hidden.x + hidden.width / 2 + 90, hidden.y + hidden.height / 2 + 140, { steps: 8 });
  await expect(frame.locator('[data-oid^="copy-"]')).toHaveCount(1);
  await page.evaluate(() => window.__zerosHarnessDesignSurface.active(false));
  await page.mouse.up();
  await page.keyboard.up("Alt");
  await page.evaluate(() => window.__zerosHarnessDesignSurface.active(true));
  await expect(frame.locator('[data-oid^="copy-"]')).toHaveCount(0);
  expect(await page.evaluate(() => window.__zerosHarnessDesignSurface.measurement.requests.filter(request => request.op === "design.transaction.apply").length)).toBe(0);
  check("hiding the canvas retires an unfinished copy without writing source", true);

  await load(page);
  await page.locator('[data-design-frame="home.html"] [data-design-frame-label]').click();
  await page.locator('[data-design-frame="pricing.html"] [data-design-frame-label]').click({ modifiers: ["Shift"] });
  const homeBeforeGroup = await home.boundingBox();
  const pricingBeforeGroup = await page.locator('[data-design-frame="pricing.html"]').boundingBox();
  const groupLabel = await home.locator('[data-design-frame-label]').boundingBox();
  await page.keyboard.down("Alt");
  await page.mouse.move(groupLabel.x + groupLabel.width / 2, groupLabel.y + groupLabel.height / 2);
  await page.mouse.down();
  await page.mouse.move(groupLabel.x + groupLabel.width / 2 + 60, groupLabel.y + groupLabel.height / 2 + 80, { steps: 10 });
  await page.mouse.up();
  await page.keyboard.up("Alt");
  await settled(page);
  expect(await home.boundingBox()).toEqual(homeBeforeGroup);
  expect(await page.locator('[data-design-frame="pricing.html"]').boundingBox()).toEqual(pricingBeforeGroup);
  await expect(page.getByText("Copy one canvas frame at a time", { exact: true })).toBeVisible();
  check("an unsupported canvas group copy never moves the originals", true);

  frame = await load(page);
  await hold(page);
  await viewport.focus();
  await page.keyboard.press("Control+d");
  await expect(copies(frame)).toHaveCount(1);
  await page.keyboard.press("Backspace");
  await release(page);
  await settled(page);
  await expect(copies(frame)).toHaveCount(0);
  await expect(frame.locator('[data-oid="home-hero"]')).toHaveCount(1);
  check("Delete immediately after a pending layer copy preserves the original", true);

  await load(page);
  await home.locator('[data-design-frame-label]').click();
  await page.evaluate(() => window.__zerosHarnessDesignSurface.measurement.hold("design.frame.duplicate"));
  await viewport.focus();
  await page.keyboard.press("Control+d");
  await page.keyboard.press("Backspace");
  await page.keyboard.press("Backspace");
  await page.evaluate(() => window.__zerosHarnessDesignSurface.measurement.release("design.frame.duplicate"));
  await settled(page);
  await expect(home).toHaveCount(1);
  await expect(page.locator('[data-design-frame="copy-1.html"]')).toHaveCount(0);
  check("Delete immediately after a pending canvas frame copy preserves the original", true);
}
