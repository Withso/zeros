import { build, transform } from "esbuild";
import { mkdir, readFile, realpath, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const SANDBOX = "scripts/cloud-workspace-validation/sandbox";
export const QUALIFICATION_BUNDLE = "dist-engine/cloud-qualification-roles.mjs";
export const BOOT_CONTRACT_BUNDLE = "dist-engine/cloud-boot-contract.mjs";
const MODULES = [
  "cloud-qualification-runtime.ts",
  "qualify-cloud-actor-tools.ts",
  "qualify-cloud-capture.ts",
  "qualify-cloud-human-services.ts",
  "qualify-cloud-runners.ts",
  // The offline closure probe also exercises the serialized identity check.
  "cloud-role-identity.ts",
];

/** Only cloud artifact recipes call this. Keep one graph, native packages
 * external, and original module URLs for createRequire, sibling assets and
 * standalone-entry guards. No qualification check or proof is precomputed. */
export async function buildCloudQualificationRoles(source = process.cwd(), output) {
  source = await realpath(source);
  output ??= path.join(source, QUALIFICATION_BUNDLE);
  const pkg = JSON.parse(await readFile(path.join(source, "package.json"), "utf8"));
  const result = await build({
    absWorkingDir: source,
    stdin: {
      contents: MODULES.map(name => `export * from ${JSON.stringify(`./${name}`)};`).join("\n"),
      resolveDir: path.join(source, SANDBOX),
      sourcefile: "cloud-qualification-roles-entry.ts",
      loader: "ts",
    },
    bundle: true,
    platform: "node",
    format: "esm",
    target: "node22",
    // Keep root runtime packages (including native modules) installed. Bundle
    // workspace TypeScript and its private transitive dependencies; flattening
    // those to bare imports would resolve them from the wrong package owner.
    external: Object.keys(pkg.dependencies ?? {}).filter(name => !name.startsWith("@zeros/") && !["zod", "jose"].includes(name)),
    keepNames: true,
    write: false,
    metafile: true,
    logLevel: "silent",
    banner: { js: "// Generated by runtime-bundle/qualification.mjs from the pinned runtime source.\n" +
      "import { createRequire as __zerosQualificationRequire } from 'node:module';\n" +
      "const require = __zerosQualificationRequire(import.meta.url);" },
    plugins: [{
      name: "cloud-qualification-source-layout",
      setup(builder) {
        builder.onLoad({ filter: /\.[cm]?[jt]s$/ }, async args => {
          const contents = await readFile(args.path, "utf8");
          if (!contents.includes("import.meta.url")) return;
          const relative = path.relative(source, args.path).split(path.sep).join("/");
          if (relative.startsWith("../") || path.isAbsolute(relative) || contents.includes("__zerosQualificationModuleUrl"))
            throw new Error("Cloud qualification source layout is unavailable");
          const transformed = await transform(contents, {
            loader: /\.[cm]?ts$/.test(args.path) ? "ts" : "js",
            format: "esm", target: "node22",
            define: { "import.meta.url": "__zerosQualificationModuleUrl" },
          });
          const url = path.posix.relative(path.posix.dirname(QUALIFICATION_BUNDLE), relative);
          return { contents: `const __zerosQualificationModuleUrl = new URL(${JSON.stringify(url)}, import.meta.url).href;\n${transformed.code}`,
            loader: "js", resolveDir: path.dirname(args.path) };
        });
      },
    }],
  });
  if (result.warnings.length || result.outputFiles.length !== 1)
    throw new Error("Cloud qualification graph did not compile");
  await mkdir(path.dirname(output), { recursive: true });
  await writeFile(output, result.outputFiles[0].contents, { mode: 0o644 });
  return result.metafile;
}

/** Compile the unchanged Q1a schema and local v3 proof contract separately.
 * No role graph, dynamic transform, executable discovery or admission runs. */
export async function buildCloudBootContract(source = process.cwd(), output) {
  source = await realpath(source);
  output ??= path.join(source, BOOT_CONTRACT_BUNDLE);
  const result = await build({ absWorkingDir: source, entryPoints: [`${SANDBOX}/cloud-boot-contract.ts`],
    bundle: true, platform: "node", format: "esm", target: "node22", write: false, metafile: true, logLevel: "silent",
    banner: { js: "// Generated by runtime-bundle/qualification.mjs from the pinned Q1a and local boot contracts." } });
  if (result.warnings.length || result.outputFiles.length !== 1) throw new Error("Cloud boot contract did not compile");
  await mkdir(path.dirname(output), { recursive: true });
  await writeFile(output, result.outputFiles[0].contents, { mode: 0o644 });
  return result.metafile;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  (async () => {
    if (process.argv.length === 2) await buildCloudQualificationRoles();
    else if (process.argv.length !== 3 || process.argv[2] !== "--boot-contract-only") throw new Error();
    await buildCloudBootContract();
  })().catch(() => {
    console.error("Cloud qualification graph did not compile");
    process.exitCode = 1;
  });
}
