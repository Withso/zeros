const SCENE_POSE_SETS: ReadonlyArray<StoryShimmerPoseDot[][]> = [
  catMouse,
  eyesRolling,
  rowerBoat,
  trainSteam,
  mountainSunrise,
];

function poseMap(pose: StoryShimmerPoseDot[]): Map<string, StoryShimmerPoseDot> {
  return new Map(pose.map((cell) => [`${cell.x}:${cell.y}`, cell]));
}

function interpolatedMotionPose(
  keyPoses: StoryShimmerPoseDot[][],
  frame: number,
): StoryShimmerPoseDot[] {
  const exactKey =
    (frame / Math.max(1, ACTION_FRAMES - 1)) * (keyPoses.length - 1);
  const fromIndex = Math.floor(exactKey);
  const toIndex = Math.min(keyPoses.length - 1, fromIndex + 1);
  const blend = smoothstep(exactKey - fromIndex);
  const from = poseMap(keyPoses[fromIndex]);
  const to = poseMap(keyPoses[toIndex]);
  const keys = new Set([...from.keys(), ...to.keys()]);
  const result: StoryShimmerPoseDot[] = [];

  for (const key of keys) {
    const fromCell = from.get(key);
    const toCell = to.get(key);
    const anchor = (fromCell ?? toCell) as StoryShimmerPoseDot;
    const alpha = (fromCell ? 1 - blend : 0) + (toCell ? blend : 0);
    if (alpha < 0.025) continue;
    result.push({
      alpha: clamp(alpha, 0, 1),
      radius:
        (fromCell?.radius ?? anchor.radius) * (1 - blend) +
        (toCell?.radius ?? anchor.radius) * blend,
      x: anchor.x,
      y: anchor.y,
    });
  }

  return result.sort(
    (first, second) => first.y - second.y || first.x - second.x,
  );
}

function relayWipePose(
  fromPose: StoryShimmerPoseDot[],
  toPose: StoryShimmerPoseDot[],
  progress: number,
): StoryShimmerPoseDot[] {
  const from = poseMap(fromPose);
  const to = poseMap(toPose);
  const keys = new Set([...from.keys(), ...to.keys()]);
  const eased = smoothstep(progress);
  const threshold = -9 + eased * 18;
  const feather = 1.2;
  const result: StoryShimmerPoseDot[] = [];

  for (const key of keys) {
    const fromCell = from.get(key);
    const toCell = to.get(key);
    const anchor = (fromCell ?? toCell) as StoryShimmerPoseDot;
    const diagonal = anchor.x + anchor.y * 0.32;
    const toAlpha = clamp((threshold - diagonal + feather) / (feather * 2), 0, 1);
    const fromAlpha = 1 - toAlpha;
    const alpha = Math.max(fromCell ? fromAlpha : 0, toCell ? toAlpha : 0);
    if (alpha < 0.04) continue;
    result.push({
      alpha,
      radius: Math.max(fromCell?.radius ?? 0, toCell?.radius ?? 0),
      x: anchor.x,
      y: anchor.y,
    });
  }

  return result.sort(
    (first, second) => first.y - second.y || first.x - second.x,
  );
}

function buildPoses(): StoryShimmerPoseDot[][] {
  const poses: StoryShimmerPoseDot[][] = [];
  for (let sceneIndex = 0; sceneIndex < SCENE_POSE_SETS.length; sceneIndex += 1) {
    const scene = SCENE_POSE_SETS[sceneIndex];
    const nextScene = SCENE_POSE_SETS[(sceneIndex + 1) % SCENE_POSE_SETS.length];
    for (let frame = 0; frame < ACTION_FRAMES; frame += 1) {
      poses.push(interpolatedMotionPose(scene, frame));
    }
    const fromPose = poses[poses.length - 1];
    for (let frame = 0; frame < TRANSITION_FRAMES; frame += 1) {
      poses.push(
        relayWipePose(fromPose, nextScene[0], (frame + 1) / (TRANSITION_FRAMES + 1)),
      );
    }
  }
  return poses;
}

function makeTransitions(
  poses: StoryShimmerPoseDot[][],
): StoryShimmerTransitionDot[][] {
  return poses.map((fromPose, poseIndex) => {
    const from = poseMap(fromPose);
    const to = poseMap(poses[(poseIndex + 1) % poses.length]);
    const keys = new Set([...from.keys(), ...to.keys()]);
    return [...keys]
      .map((key) => {
        const fromCell = from.get(key);
        const toCell = to.get(key);
        const anchor = (fromCell ?? toCell) as StoryShimmerPoseDot;
        return {
          fromAlpha: fromCell?.alpha ?? 0,
          fromRadius: (fromCell ?? anchor).radius,
          toAlpha: toCell?.alpha ?? 0,
          toRadius: (toCell ?? anchor).radius,
          x: anchor.x,
          y: anchor.y,
        };
      })
      .sort((first, second) => first.y - second.y || first.x - second.x);
  });
}

export const STORY_SHIMMER_POSES: ReadonlyArray<
  ReadonlyArray<StoryShimmerPoseDot>
> = buildPoses();

export const STORY_SHIMMER_FRAME_COUNT = STORY_SHIMMER_POSES.length;

export const STORY_SHIMMER_TRANSITIONS: ReadonlyArray<
  ReadonlyArray<StoryShimmerTransitionDot>
> = makeTransitions(STORY_SHIMMER_POSES as StoryShimmerPoseDot[][]);

/** Diagonal projection driving the traveling highlight band. Constants match
 *  the approved prototype (story-shimmer.js) so the sweep feel is identical. */
export function storyShimmerProjection(x: number, y: number): number {
  return (x + 7 + (y + 7) * 0.38) / (14 * 1.38);
}
