  function clamp(value, minimum, maximum) {
    return Math.min(maximum, Math.max(minimum, value));
  }

  function unpackPose(flatPose) {
    const pose = new Map();
    for (let index = 0; index < flatPose.length; index += 3) {
      pose.set(
        `${flatPose[index]}:${flatPose[index + 1]}`,
        flatPose[index + 2],
      );
    }
    return pose;
  }

  function catmullRom(previous, from, to, next, progress) {
    const progress2 = progress * progress;
    const progress3 = progress2 * progress;
    return (
      0.5 *
      (2 * from +
        (-previous + to) * progress +
        (2 * previous - 5 * from + 4 * to - next) * progress2 +
        (-previous + 3 * from - 3 * to + next) * progress3)
    );
  }

  function densifyPoseCycle(sourcePoses, subdivision) {
    const sourceMaps = sourcePoses.map(unpackPose);
    const poses = [];
    const names = [];

    for (let poseIndex = 0; poseIndex < sourcePoses.length; poseIndex += 1) {
      const previous = sourceMaps.at(poseIndex - 1);
      const from = sourceMaps[poseIndex];
      const to = sourceMaps[(poseIndex + 1) % sourceMaps.length];
      const next = sourceMaps[(poseIndex + 2) % sourceMaps.length];
      const keys = new Set([
        ...previous.keys(),
        ...from.keys(),
        ...to.keys(),
        ...next.keys(),
      ]);
      const coordinates = [...keys]
        .map((key) => key.split(":").map(Number))
        .sort((a, b) => a[1] - b[1] || a[0] - b[0]);

      for (let step = 0; step < subdivision; step += 1) {
        const progress = step / subdivision;

        if (step === 0) {
          poses.push(sourcePoses[poseIndex].slice());
          names.push(`${POSE_NAMES[poseIndex]}-key`);
          continue;
        }

        const pose = [];
        for (const [x, y] of coordinates) {
          const key = `${x}:${y}`;
          const radius = Math.round(
            clamp(
              catmullRom(
                previous.get(key) || 0,
                from.get(key) || 0,
                to.get(key) || 0,
                next.get(key) || 0,
                progress,
              ),
              0,
              255,
            ),
          );
          if (radius < 5) continue;
          pose.push(x, y, radius);
        }

        poses.push(pose);
        names.push(`${POSE_NAMES[poseIndex]}-inbetween-${step}`);
      }
    }

    return { names, poses };
  }

