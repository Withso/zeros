// Cross-tool branch interop. Detects branches + worktrees created by
// other AI coding tools so a Zeros user can see and adopt them.
// The tool ids below are the `DetectedTool` values persisted on a
// workspace row, so they are contract, not cosmetics.
//
// Detection is best-effort and layered:
//
//   1. Read every linked worktree from `git worktree list --porcelain`.
//      Zeros's own worktrees are recognised from the engine state DB /
//      managed worktree root (the in-tree .zeros/workspace.json marker was
//      retired). Other tools are still probed by a known marker file:
//        - <wt>/.cursor/worktrees.json        → cursor
//        - <wt>/.superset/config.json         → superset
//        - <wt>/.conductor/*                  → conductor
//   2. For branches that aren't checked out anywhere, fall back to
//      naming heuristics:
//        - "zeros/*"                          → zeros
//        - "cursor/*"                         → cursor
//        - single-word city name              → conductor
//        - others                             → unknown
//   3. User-level marker files are checked independently for integrations
//      that do not write state inside the worktree.

